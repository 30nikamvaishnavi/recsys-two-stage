"""Render docs/results.md from the JSON reports in artifacts/reports/<mode>/. Only real, computed
numbers are written; a missing report is shown as 'not run yet'."""
from __future__ import annotations

from pathlib import Path

from recsys.config import ROOT, parse_cfg, path
from recsys.utils import load_json


def _load(p: Path):
    return load_json(p) if p.exists() else None


def f(x, d=4):
    return "n/a" if x is None or x != x else f"{x:.{d}f}"


def main():
    cfg, _ = parse_cfg("Generate docs/results.md")
    rd = Path(path(cfg, "reports"))
    L = [f"# Results ({cfg['mode']} mode)\n", "_Generated by `make report` from `artifacts/reports/`. Nothing here is typed by hand._\n"]
    ds = _load(Path(path(cfg, "data_processed")) / "dataset_stats.json")
    if ds:
        L += ["## Dataset\n", f"- users {ds['users']:,}, items {ds['items']:,}, interactions {ds['interactions']:,}, positive rate {ds['positive_rate']:.3f}",
              f"- interactions per time stage: {ds['per_stage']}\n"]  # fmt: skip
    r = _load(rd / "retrieval_metrics.json")
    L.append("## Retrieval (time-based validation window, warm users)\n")
    if r:
        L += ["| model | recall@10 | recall@50 | recall@100 | NDCG@10 |", "|---|---|---|---|---|"]
        for k, n in (("popularity", "Popularity"), ("svd_mf", "SVD matrix factorisation"), ("two_tower", "Two-tower (TFRS)")):
            m = r[k]
            L.append(f"| {n} | {f(m['recall@10'])} | {f(m['recall@50'])} | {f(m['recall@100'])} | {f(m['ndcg@10'])} |")
        c = r.get("cold_item_embeddings", {})
        if c.get("n_users"):
            L.append(f"\nCold items (content-only embeddings), recall@100 on cold targets: {f(c.get('recall@100'))} over {c['n_users']} users (popularity cannot retrieve them).")
    else:
        L.append("not run yet")
    b = _load(rd / "faiss_benchmark.json")
    L.append("\n## ANN index (FAISS)\n")
    if b:
        L += ["| index | recall@100 vs exact | p50 ms | p95 ms | memory MB |", "|---|---|---|---|---|"]
        for x in b["results"]:
            L.append(f"| {x['name']} | {f(x['recall@100'], 3)} | {f(x['p50'], 3)} | {f(x['p95'], 3)} | {f(x['memory_mb'], 1)} |")
        L.append(f"\nChosen: **{b['chosen']['name']}** ({'FAISS' if b['faiss'] else 'NumPy exact fallback - FAISS not installed'}). Plot: `faiss_benchmark.png`.")
    else:
        L.append("not run yet")
    k = _load(rd / "ranking_metrics.json")
    L.append("\n## Ranking (val candidates)\n")
    if k:
        L += ["| ordering | NDCG@10 | recall@10 | MAP@10 | AUC | logloss |", "|---|---|---|---|---|---|"]
        any_m = next(iter(k["models"].values()))
        ro = any_m["retrieval_only"]
        L.append(f"| retrieval score only | {f(ro['ndcg@10'])} | {f(ro['recall@10'])} | {f(ro['map@10'])} | - | - |")
        for n, v in k["models"].items():
            m = v["ranker"]
            L.append(f"| {n} | {f(m['ndcg@10'])} | {f(m['recall@10'])} | {f(m['map@10'])} | {f(m['auc'])} | {f(m['logloss'])} |")
        L += ["\n### Ablation (DCN-V2, drop one feature group)\n", "| variant | NDCG@10 | recall@10 | MAP@10 | AUC |", "|---|---|---|---|---|"]
        for n, m in k["ablations"].items():
            L.append(f"| {n} | {f(m['ndcg@10'])} | {f(m['recall@10'])} | {f(m['map@10'])} | {f(m['auc'])} |")
        L.append("\nCalibration (ECE): " + ", ".join(f"{n}={f(v['calibration']['ece'])}" for n, v in k["models"].items()) + " (training base rate is inflated by candidate sampling; see limitations).")
    else:
        L.append("not run yet")
    cs = _load(rd / "coldstart_metrics.json")
    L.append("\n## Cold start (NDCG@10 by number of known interactions)\n")
    if cs:
        strategies = sorted({s for v in cs["users"]["by_history_len"].values() for s in v})
        L += ["| #interactions | " + " | ".join(strategies) + " |", "|---|" + "---|" * len(strategies)]
        for n, v in cs["users"]["by_history_len"].items():
            L.append(f"| {n} | " + " | ".join(f(v[s]["ndcg@10"]) if s in v else "-" for s in strategies) + " |")
    else:
        L.append("not run yet")
    a = _load(rd / "ab_results.json")
    L.append("\n## Simulated A/B test (A = Wide&Deep, B = DCN-V2) - SIMULATION, not real users\n")
    if a:
        L += ["| arm | users | CTR | NDCG@10 | recall@10 |", "|---|---|---|---|---|"]
        for n, m in a["arms"].items():
            L.append(f"| {n} ({m['variant']}) | {a['n_users'][n]} | {f(m['ctr'])} [{f(m['ctr_user_level']['ci_low'])}, {f(m['ctr_user_level']['ci_high'])}] | {f(m['ndcg@10']['mean'])} [{f(m['ndcg@10']['ci_low'])}, {f(m['ndcg@10']['ci_high'])}] | {f(m['recall@10']['mean'])} |")
        t = a["tests"]
        L.append(f"\n- CTR z-test p = {f(t['ctr_two_proportion_z']['p_value'])}; user-level bootstrap diff {f(t['ctr_bootstrap_user_level']['diff'])} CI [{f(t['ctr_bootstrap_user_level']['ci_low'])}, {f(t['ctr_bootstrap_user_level']['ci_high'])}]")
        L.append(f"- A/A false-positive rate {f(a['aa_false_positive_rate'], 3)} (should be ~{a['decision']['alpha']}); MDE (abs CTR) {f(a['mde_ctr_abs'])}")
        L.append(f"- **Decision: {a['decision']['decision']}** - {a['decision']['reason']}")
    else:
        L.append("not run yet")
    for name, title in (("load_test.json", "Load test"), ("cache_benchmark.json", "Cache benchmark")):
        d = _load(rd / name)
        L.append(f"\n## {title}\n")
        L.append("```json\n" + __import__("json").dumps(d, indent=2) + "\n```" if d else "not run yet")
    out = ROOT / "docs" / f"results_{cfg['mode']}.md"
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
