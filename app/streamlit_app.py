"""Streamlit demo: side-by-side model comparison, per-stage latency, explanations, A/B dashboard."""

from __future__ import annotations

import json
import os
import zlib
from pathlib import Path

import pandas as pd
import requests
import streamlit as st

API = os.environ.get("API_URL", "http://localhost:8080")
MODE = os.environ.get("RECSYS_MODE", "sample")
REPORTS = Path(os.environ.get("RECSYS_HOME", ".")) / "artifacts" / "reports" / MODE
st.set_page_config(page_title="Two-stage recommender", layout="wide")


def recs(payload):
    return requests.post(f"{API}/recommend", json=payload, timeout=30).json()


def show(res, title):
    m = res["meta"]
    st.subheader(title)
    st.caption(
        f"strategy **{m['strategy']}** | reason `{m['reason_code']}` | cache hit: {m['cache_hit']} | total {m['latency_ms']['total']:.1f} ms"
    )
    df = pd.DataFrame(res["items"])
    df.index = df.index + 1
    st.dataframe(
        df[["title", "genres", "score", "retrieval_score", "ranker_score"]],
        use_container_width=True,
    )
    lat = pd.Series({k: v for k, v in m["latency_ms"].items() if k != "total"}, name="ms")
    st.bar_chart(lat)


try:
    health = requests.get(f"{API}/health", timeout=5).json()
except Exception as e:
    st.error(f"API not reachable at {API}: {e}")
    st.stop()

st.sidebar.title("Recommender")
st.sidebar.json(health)
tab1, tab2, tab3, tab4 = st.tabs(["Recommend", "Similar items", "A/B results", "Offline results"])

with tab1:
    mode = st.radio("User", ["Existing user", "New user (cold start)"], horizontal=True)
    k = st.slider("k", 5, 30, 10)
    if mode == "Existing user":
        uid = st.number_input("MovieLens userId", min_value=1, value=1, step=1)
        use_cache = st.checkbox("Use Redis cache", True)
        payload = {"user_id": int(uid), "k": k, "use_cache": use_cache}
    else:
        genres = st.multiselect(
            "Favourite genres", requests.get(f"{API}/genres").json(), default=["Sci-Fi", "Thriller"]
        )
        payload = {
            "user_id": 10**9 + zlib.crc32(",".join(sorted(genres)).encode()) % 10**6,
            "k": k,
            "onboarding_genres": genres,
        }
    if st.button("Recommend", type="primary"):
        c1, c2 = st.columns(2)
        with c1:
            show(recs({**payload, "model_variant": "wide_deep"}), "A - Wide & Deep")
        with c2:
            show(recs({**payload, "model_variant": "dcn_v2"}), "B - DCN-V2")
        st.info("Why these items? `retrieval_score` = two-tower cosine similarity; `ranker_score` = P(positive) from the ranking model; "
                "the final order also applies MMR diversity. Cold users skip the models and use popularity / content fallbacks (see reason code).")  # fmt: skip
        st.json(requests.get(f"{API}/cache/stats").json())

with tab2:
    mid = st.number_input("MovieLens movieId", min_value=1, value=100, step=1)
    if st.button("Find similar"):
        r = requests.get(f"{API}/similar-items", params={"item_id": int(mid), "k": 10})
        st.dataframe(pd.DataFrame(r.json())) if r.ok else st.error(r.text)

with tab3:
    p = REPORTS / "ab_results.json"
    if p.exists():
        a = json.loads(p.read_text())
        st.warning(
            "SIMULATION: clicks are generated by a position-biased click model from held-out interactions; there are no real users."
        )
        rows = [{"arm": n, "variant": m["variant"], "users": a["n_users"][n], "CTR": m["ctr"], "CTR CI": f"[{m['ctr_user_level']['ci_low']:.4f}, {m['ctr_user_level']['ci_high']:.4f}]",
                 "NDCG@10": m["ndcg@10"]["mean"], "recall@10": m["recall@10"]["mean"]} for n, m in a["arms"].items()]  # fmt: skip
        st.dataframe(pd.DataFrame(rows))
        st.metric("Decision", a["decision"]["decision"], a["decision"]["reason"])
        st.json(a["tests"])
    else:
        st.info("Run `make abtest` first.")

with tab4:
    for name in (
        "retrieval_metrics",
        "ranking_metrics",
        "coldstart_metrics",
        "load_test",
        "cache_benchmark",
    ):
        p = REPORTS / f"{name}.json"
        if p.exists():
            with st.expander(name):
                st.json(json.loads(p.read_text()))
    for img in ("faiss_benchmark.png", "ranker_calibration.png"):
        if (REPORTS / img).exists():
            st.image(str(REPORTS / img))
